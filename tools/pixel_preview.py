def battery_level(percent):
    """Return the firmware's inclusive 0..20 through 81..100 icon band."""
    if percent < 0:
        return 1
    percent = min(100, percent)
    return 1 if percent == 0 else (percent + 19) // 20


def draw_battery(canvas, font, percent, cy, external_power=False):
    """The battery texture chosen by percent + external power, alongside %.

    Mirrors drawBattery() in dashboard_ui.h. Both pull their pixel data from
    battery_icon_data.py so the preview cannot drift from the firmware.
    """
    display_percent = -1 if percent < 0 else min(100, percent)
    label = "--%" if display_percent < 0 else f"{display_percent}%"
    icon_w = BATTERY["icon_w"]
    icon_h = BATTERY["icon_h"]
    gap = BATTERY["gap"]

    # Pick the icon. Level 1 is the lowest visible state; 100% is level 5.
    level = battery_level(display_percent)
    table = battery_icon_data.BATTERY_CHARGING if external_power \
        else battery_icon_data.BATTERY_IDLE
    words, alpha_bytes = table[level - 1]

    tw = canvas.text_width(font, label, 1)
    left = 180 - (icon_w + gap + tw) // 2
    top = cy - icon_h // 2
    canvas.texture_at(words, alpha_bytes, left, top, icon_w, icon_h)

    canvas.text(font, label, left + icon_w + gap, cy, 1, TEXT)


def draw_panel(canvas, font, scene):
    """The information panel -- or the setup prompt, which takes its place.

    Mirrors drawPanel() in dashboard_ui.h. The two branches are exclusive
    rather than layered: link health and quota are both meaningless before the
    device is on a network, so the setup prompt replaces them and reuses the
    same four rows, leaving the layout where it was.
    """
    canvas.pixel_frame(PANEL["x"], PANEL["y"], PANEL["w"], PANEL["h"],
                       FRAME, FILL, cut=PANEL["cut"], thickness=2)

    if scene.get("setup"):
        canvas.text(font, "WIFI SETUP", 180, STATUS_LINE["cy"], 1, WARNING,
                    centre=True)
        canvas.text(font, scene["setup_ssid"], 180, QUOTA["cy"], 1,
                    ACCENT_GREEN, centre=True)
        canvas.text(font, "OPEN BROWSER", 180, SEND["cy"], 1, DIM, centre=True)
        canvas.text(font, "192.168.4.1", 180, COUNTDOWN["cy"], 1, TEXT,
                    centre=True)
        return

    draw_battery(canvas, font, scene["battery"], BATTERY["cy"],
                 external_power=scene.get("external_power", False))
    canvas.rect(DIVIDER_X0, DIVIDER_Y, DIVIDER_X1 - DIVIDER_X0, 1, DIVIDER)

    canvas.text(font, scene["status"], 180, STATUS_LINE["cy"],
                STATUS_LINE["scale"], ACCENT_GREEN, centre=True)
    canvas.text(font, scene["quota"], 180, QUOTA["cy"],
                QUOTA["scale"], TEXT, centre=True)
    canvas.text(font, scene["send"], 180, SEND["cy"],
                SEND["scale"], DIM, centre=True)
    canvas.text(font, scene["countdown"], 180, COUNTDOWN["cy"],
                COUNTDOWN["scale"], TEXT, centre=True)


def render(scene, font, textures, background=None):
    canvas = Canvas(background)

    canvas.text_outlined(font, scene["clock"], CLOCK["cx"], CLOCK["cy"],
                         CLOCK["scale"], TEXT, OUTLINE, thickness=2,
                         centre=True)
    canvas.text_outlined(font, scene["date"], DATE["cx"], DATE["cy"],
                         DATE["scale"], TEXT, OUTLINE, thickness=1,
                         centre=True)

    draw_panel(canvas, font, scene)

    for index, (state, tag) in enumerate(scene["agents"]):
        cx = BTN_COLS[index % 3]
        cy = BTN_ROWS[index // 3]
        colour = STATUS[state]
        x, y = cx - BTN_W // 2, cy - BTN_H // 2
        canvas.pixel_frame(x, y, BTN_W, BTN_H, colour, FILL,
                           cut=BTN_CUT, thickness=2)
        words, alphas = textures[state]
        canvas.texture(words, alphas, x + BTN_ICON_DX, cy)
        canvas.text(font, tag, x + BTN_TEXT_DX, cy + BTN_TAG_DY, 2, colour,
                    centre=True)
        canvas.text(font, state, x + BTN_TEXT_DX, cy + BTN_LABEL_DY, 1, colour,
                    centre=True)

    # The motto sits on open scene, not on a panel, so it needs the same halo as
    # the clock: over the day theme's grass a bare dim grey is unreadable.
    canvas.text_outlined(font, "GOOD IDEAS", 180, MOTTO[0], 1, DIM, OUTLINE,
                         thickness=1, centre=True)
    canvas.text_outlined(font, "TAKE TIME", 180, MOTTO[1], 1, DIM, OUTLINE,
                         thickness=1, centre=True)
    return canvas


def apply_round_mask(canvas):
    """Blank everything outside the visible circle, as the round panel does."""
    r = WIDTH / 2.0
    for y in range(HEIGHT):
        dy = y + 0.5 - r
        for x in range(WIDTH):
            dx = x + 0.5 - r
            if dx * dx + dy * dy > r * r:
                i = (y * WIDTH + x) * 3
                canvas.px[i:i + 3] = bytes((0, 0, 0))


def load_background(path: str):
    """Load a 360x360 background PNG as raw RGB, or None if absent."""
    if not path or not os.path.exists(path):
        return None
    with open(path, "rb") as handle:
        data = handle.read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise SystemExit(f"{path}: not a PNG")
    pos, idat, width, height, depth, ctype = 8, b"", 0, 0, 0, 0
    while pos < len(data):
        length = struct.unpack(">I", data[pos:pos + 4])[0]
        tag = data[pos + 4:pos + 8]
        body = data[pos + 8:pos + 8 + length]
        if tag == b"IHDR":
            width, height, depth, ctype = struct.unpack(">IIBB", body[:10])
        elif tag == b"IDAT":
            idat += body
        elif tag == b"IEND":
            break
        pos += 12 + length
    if (width, height) != (WIDTH, HEIGHT) or depth != 8 or ctype != 2:
        raise SystemExit(f"{path}: need 8-bit RGB {WIDTH}x{HEIGHT}, "
                         f"got {width}x{height} depth {depth} type {ctype}")
    raw = zlib.decompress(idat)
    out = bytearray(WIDTH * HEIGHT * 3)
    stride = WIDTH * 3
    prev = bytearray(stride)
    for y in range(HEIGHT):
        start = y * (stride + 1)
        filter_type = raw[start]
        line = bytearray(raw[start + 1:start + 1 + stride])
        for i in range(stride):
            a = line[i - 3] if i >= 3 else 0
            b = prev[i]
            c = prev[i - 3] if i >= 3 else 0
            if filter_type == 1:
                line[i] = (line[i] + a) & 0xFF
            elif filter_type == 2:
                line[i] = (line[i] + b) & 0xFF
            elif filter_type == 3:
                line[i] = (line[i] + (a + b) // 2) & 0xFF
            elif filter_type == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pred = a if (pa <= pb and pa <= pc) else (b if pb <= pc else c)
                line[i] = (line[i] + pred) & 0xFF
        out[y * stride:(y + 1) * stride] = line
        prev = line
    return out


def write_png(path: str, canvas: Canvas):
    raw = bytearray()
    for y in range(HEIGHT):
        raw.append(0)
        raw += canvas.px[y * WIDTH * 3:(y + 1) * WIDTH * 3]

    def chunk(tag: bytes, data: bytes) -> bytes:
        return (struct.pack(">I", len(data)) + tag + data
                + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF))

    png = (b"\x89PNG\r\n\x1a\n"
           + chunk(b"IHDR", struct.pack(">IIBBBBB", WIDTH, HEIGHT, 8, 2, 0, 0, 0))
           + chunk(b"IDAT", zlib.compress(bytes(raw), 9))
           + chunk(b"IEND", b""))
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "wb") as handle:
        handle.write(png)


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter)
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    parser.add_argument("--scene", default="all", choices=["all", *SCENES])
    parser.add_argument("--at", default=None, metavar="HH:MM",
                        help="local wall-clock time; picks the theme by rule "
                             "and fills the clock/date fields")
    parser.add_argument("--rule", action="store_true",
                        help="print the theme rule's boundaries and exit")
    parser.add_argument("--out", default=None)
    parser.add_argument("--no-round-mask", action="store_true")
    args = parser.parse_args()

    if args.rule:
        print(f"local time = UTC+{TZ_OFFSET_HOURS} (no DST)")
        print(f"night  >= {NIGHT_START_HOUR:02d}:00")
        print(f"day    >= {DAY_START_HOUR:02d}:00")
        print()
        for hour in range(24):
            print(f"  {hour:02d}:00  {theme_for(hour)}")
        return 0

    font = load_font(root, "kPixel8Vlw")
    textures = load_textures(root)
    print(f"font: {font.count} glyphs, {font.size} px em, "
          f"ascent {font.ascent} descent {font.descent}")
    print(f"icons: {', '.join(sorted(textures))} "
          f"({ICON_SIZE}x{ICON_SIZE} RGB565+A8)")

    if args.at:
        hour, _, minute = args.at.partition(":")
        hour, minute = int(hour), int(minute or 0)
        theme = theme_for(hour, minute)
        import datetime
        now = datetime.datetime(2026, 9, 23, hour, minute)
        print(f"at {args.at} local -> {theme} theme, "
              f"clock {format_clock(now)}, date {format_date(now)}")
        scenes = {theme: dict(SCENES[theme],
                              clock=format_clock(now),
                              date=format_date(now))}
    else:
        scenes = SCENES if args.scene == "all" \
            else {args.scene: SCENES[args.scene]}
    out_dir = args.out or os.path.join(root, "tools", "preview")
    for name, scene in scenes.items():
        bg_path = os.path.join(root, "tools", "preview", scene["bg"])
        background = load_background(bg_path)
        print(f"background: {'loaded ' + scene['bg'] if background else 'none (flat void)'}")
        canvas = render(scene, font, textures, background)
        if not args.no_round_mask:
            apply_round_mask(canvas)
        path = args.out if (args.out and len(scenes) == 1) \
            else os.path.join(out_dir, f"pixel-{name}.png")
        write_png(path, canvas)
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
