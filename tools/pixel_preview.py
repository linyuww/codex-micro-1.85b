#!/usr/bin/env python3
"""Offline renderer for the pixel-art dashboard, at 360x360.

Mirrors what the firmware will do: the same VLW blob parser as gfx.cpp, the same
8 px Press Start 2P em scaled by integer factors, the same 20 px A8 icon masks
from IconMask.h. Its job is to let the layout be judged on a PC before anything
is flashed.

Every geometry constant below was measured off the ChatGPT mockups rather than
eyeballed. The measurement method matters, so it is recorded here: the day and
night mockups share an identical UI skeleton and differ only in the background
scene, so |day - night| isolates the background and its complement isolates the
chrome. Frames were then located by walking single rows and columns and
recording where a saturated accent hue appears -- far more robust than bounding
boxes, which the background art bleeds into.

Colours are sampled from the mockups and quantised to RGB565, so the preview
shows what the panel will actually show. Text is drawn at integer scales only
(1x = 8 px, 2x = 16, 3x = 24, 4x = 32). Every glyph at those sizes was verified
to be a bit-exact upscale of the 8 px em, so the result is identical to
rasterising natively while costing a single 8 KB font.

    python tools/pixel_preview.py
    python tools/pixel_preview.py --scene night --out C:\\tmp\\preview.png
"""

