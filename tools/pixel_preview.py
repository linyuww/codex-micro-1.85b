# ------------------------------------------------------- time and theme ---
# The clock comes from NTP over WiFi, so every time comparison in the UI is in
# LOCAL time. The board has no RTC: until the first sync the clock is unknown,
# and the theme rule must not be evaluated at all (see theme_for).
TZ_OFFSET_HOURS = 8        # UTC+8, no DST

# Two thresholds, not one. A single "switch at 19:00" leaves the other half of
# the cycle undefined -- nothing would ever switch back to day.
NIGHT_START_HOUR = 19      # >= 19:00 -> night
DAY_START_HOUR = 6         # >= 06:00 -> day

MONTHS = ("JAN", "FEB", "MAR", "APR", "MAY", "JUN",
          "JUL", "AUG", "SEP", "OCT", "NOV", "DEC")
WEEKDAYS = ("MON", "TUE", "WED", "THU", "FRI", "SAT", "SUN")


def theme_for(hour, minute=0):
    """'night' or 'day' for a local wall-clock time."""
    if hour >= NIGHT_START_HOUR or hour < DAY_START_HOUR:
        return "night"
    return "day"


def format_clock(dt):
    """24 h, zero padded -- the design shows '10:08'."""
    return f"{dt.hour:02d}:{dt.minute:02d}"


def format_date(dt):
    """'SEP 22 MON' -- the design's layout."""
    return f"{MONTHS[dt.month - 1]} {dt.day:02d} {WEEKDAYS[dt.weekday()]}"


# ------------------------------------------------------------------- font ---

class Font:
    """Parsed view over a VLW blob, mirroring gfx.cpp's Font::load."""

    def __init__(self, blob: bytes):
        self.data = blob
        (self.count, self.version, self.size, _flags,
         self.ascent, self.descent) = struct.unpack(">6i", blob[:24])
        self.base = 24 + self.count * 28
        self.glyphs = {}
        offset = 0
        for i in range(self.count):
            record = blob[24 + i * 28: 24 + (i + 1) * 28]
            code, height, width, advance, top, left, _ = struct.unpack(">7i", record)
            self.glyphs[code] = (offset, width, height, advance, top, left)
            offset += width * height

    def width(self, text: str) -> int:
        return sum(self.glyphs.get(ord(c), (0, 0, 0, self.size, 0, 0))[3]
                   for c in text)

    def bitmap(self, char: str):
        entry = self.glyphs.get(ord(char))
        if entry is None:
            return None
        offset, width, height, _adv, top, left = entry
        if width == 0 or height == 0:
            return None
        start = self.base + offset
        return self.data[start:start + width * height], width, height, top, left


def load_font(root: str, name: str) -> Font:
    source = open(os.path.join(root, "main", "PixelFonts.h"),
                  encoding="utf-8").read()
    match = re.search(r"static constexpr std::uint8_t " + name
                      + r"\[\] = \{(.*?)\};", source, re.S)
    if not match:
        raise SystemExit(f"{name} not found in PixelFonts.h")
    blob = bytes(int(x, 16)
                 for x in re.findall(r"0x([0-9A-Fa-f]{2})", match.group(1)))
    return Font(blob)


ICON_NAMES = ("kIconThink", "kIconDone", "kIconInput",
              "kIconEmpty", "kIconError", "kIconIdle")


def load_icons(root: str) -> dict:
    source = open(os.path.join(root, "main", "IconMask.h"),
                  encoding="utf-8").read()
    icons = {}
    for name in ICON_NAMES:
        match = re.search(r"static constexpr std::uint8_t " + name
                          + r"\[\] = \{(.*?)\};", source, re.S)
        if not match:
            raise SystemExit(f"{name} not found in IconMask.h")
        blob = bytes(int(x, 16)
                     for x in re.findall(r"0x([0-9A-Fa-f]{2})", match.group(1)))
        assert len(blob) == ICON_SIZE * ICON_SIZE, (name, len(blob))
        icons[name.replace("kIcon", "").upper()] = blob
    return icons


def load_textures(root: str, filename: str = "IconTextures.h") -> dict:
    """Parse IconTextures.h into premultiplied (RGB565 words, A8 coverage)."""
    source = open(os.path.join(root, "main", filename),
                  encoding="utf-8").read()
    textures = {}
    for name in ICON_NAMES:
        mw = re.search(r"static constexpr std::uint16_t " + name
                       + r"_rgb\[\] = \{(.*?)\};", source, re.S)
        ma = re.search(r"static constexpr std::uint8_t " + name
                       + r"_a\[\] = \{(.*?)\};", source, re.S)
        if not mw or not ma:
            raise SystemExit(f"{name} not found in IconTextures.h")
        words = [int(x, 16)
                 for x in re.findall(r"0x([0-9A-Fa-f]{4})", mw.group(1))]
        alphas = bytes(int(x, 16)
                       for x in re.findall(r"0x([0-9A-Fa-f]{2})", ma.group(1)))
        assert len(words) == ICON_SIZE * ICON_SIZE, (name, len(words))
        assert len(alphas) == ICON_SIZE * ICON_SIZE, (name, len(alphas))
        textures[name.replace("kIcon", "").upper()] = (words, alphas)
    return textures


# ----------------------------------------------------------------- canvas ---

class Canvas:
    def __init__(self, background=None):
        if background is None:
            self.px = bytearray(VOID * (WIDTH * HEIGHT))
        else:
            self.px = bytearray(background)

    def blend(self, x, y, colour, coverage=1.0):
        if x < 0 or y < 0 or x >= WIDTH or y >= HEIGHT or coverage <= 0:
            return
        i = (y * WIDTH + x) * 3
        if coverage >= 1.0:
            self.px[i:i + 3] = bytes(colour)
            return
        for c in range(3):
            self.px[i + c] = int(self.px[i + c]
                                 + (colour[c] - self.px[i + c]) * coverage + 0.5)

    def rect(self, x, y, w, h, colour):
        for py in range(y, y + h):
            for px_ in range(x, x + w):
                self.blend(px_, py, colour)

    def pixel_rect(self, x, y, w, h, colour, cut=3, step=2):
        """Rectangle with a stepped (chamfered) corner -- the mockup's shape.

        `cut` is the number of steps and `step` is the horizontal inset each
        one adds, so the first row is inset by cut * step and the level shrinks
        by `step` per row until it reaches zero.

        An earlier comment here claimed the mockup reads "6, 6, 4, 4, 2, 2, 0",
        i.e. two rows per level. That is not what this code does and not what
        the mockup shows. Re-measured off the raw 1254 px art
        (outputs/probe_chamfer.py): the A2 button's chamfer spans 3 levels and
        the panel's spans 4, each roughly one row tall, with total insets of
        about 5 and 9. Those totals match cut=3 and cut=4 at step=2, which is
        exactly what this computes -- so the code stood and the comment was
        wrong. Do not "fix" this to `d // step`; that doubles the chamfer's
        height and no longer matches the art.
        """
        for row in range(h):
            d = min(row, h - 1 - row)
            inset = step * (cut - min(d, cut)) if d < cut else 0
            self.rect(x + inset, y + row, w - 2 * inset, 1, colour)

    def pixel_frame(self, x, y, w, h, colour, fill, cut=3, thickness=1,
                    step=2):
        self.pixel_rect(x, y, w, h, colour, cut, step)
        self.pixel_rect(x + thickness, y + thickness,
                        w - 2 * thickness, h - 2 * thickness, fill,
                        max(0, cut - thickness), step)

    def mask(self, blob, cx, cy, colour, alpha=1.0):
        """An A8 mask, tinted and blended, centred on (cx, cy)."""
        if alpha <= 0:
            return
        x0, y0 = cx - ICON_SIZE // 2, cy - ICON_SIZE // 2
        for row in range(ICON_SIZE):
            for col in range(ICON_SIZE):
                a = blob[row * ICON_SIZE + col] / 255.0 * alpha
                if a > 0:
                    self.blend(x0 + col, y0 + row, colour, a)

    def texture(self, words, alphas, cx, cy, alpha=1.0):
        """A premultiplied RGB565+A8 texture, centred on (cx, cy).

        The artist's icons carry internal shading, so they ship as colour
        textures rather than a coverage mask plus a tint. Premultiplied
        compositing is `out = src + dst * (255 - a) / 255`, which is also what
        makes the brain's fold lines show the button background through, as the
        design does.
        """
        if alpha <= 0:
            return
        x0, y0 = cx - ICON_SIZE // 2, cy - ICON_SIZE // 2
        for row in range(ICON_SIZE):
            for col in range(ICON_SIZE):
                i = row * ICON_SIZE + col
                a = alphas[i] / 255.0 * alpha
                if a <= 0:
                    continue
                value = words[i]
                src = (((value >> 11) & 0x1F) << 3,
                       ((value >> 5) & 0x3F) << 2,
                       (value & 0x1F) << 3)
                x, y = x0 + col, y0 + row
                if x < 0 or y < 0 or x >= WIDTH or y >= HEIGHT:
                    continue
                j = (y * WIDTH + x) * 3
                if a >= 1.0:
                    self.px[j:j + 3] = bytes(src)
                    continue
                inv = 1.0 - a
                for c in range(3):
                    self.px[j + c] = min(255, int(src[c] + self.px[j + c] * inv
                                                  + 0.5))

    def texture_at(self, words, alphas, x0, y0, w, h, alpha=1.0):
        """Same as texture(), but anchored by the top-left corner.

        The status icons are 20x20 squares and want a centre point; the
        battery is a 22x12 rectangle and wants its left edge, so this method
        exists to keep both call sites readable.
        """
        if alpha <= 0:
            return
        for row in range(h):
            for col in range(w):
                i = row * w + col
                a = alphas[i] / 255.0 * alpha
                if a <= 0:
                    continue
                value = words[i]
                src = (((value >> 11) & 0x1F) << 3,
                       ((value >> 5) & 0x3F) << 2,
                       (value & 0x1F) << 3)
                x, y = x0 + col, y0 + row
                if x < 0 or y < 0 or x >= WIDTH or y >= HEIGHT:
                    continue
                j = (y * WIDTH + x) * 3
                if a >= 1.0:
                    self.px[j:j + 3] = bytes(src)
                    continue
                inv = 1.0 - a
                for c in range(3):
                    self.px[j + c] = min(255, int(src[c] + self.px[j + c] * inv
                                                  + 0.5))

    def glyph_pixels(self, font, string, x, y, scale, centre=False):
        """Every lit pixel of `string`, as an (x, y) stream."""
        baseline = y + (font.ascent - font.descent) // 2 * scale
        pen = x - (font.width(string) * scale) // 2 if centre else x
        for ch in string:
            glyph = font.bitmap(ch)
            if glyph is None:
                pen += font.glyphs.get(
                    ord(ch), (0, 0, 0, font.size, 0, 0))[3] * scale
                continue
            bitmap, gw, gh, top, left = glyph
            gx, gy = pen + left * scale, baseline - top * scale
            for row in range(gh * scale):
                source_row = row // scale
                for col in range(gw * scale):
                    if bitmap[source_row * gw + col // scale]:
                        yield gx + col, gy + row
            pen += font.glyphs[ord(ch)][3] * scale

    def text_outlined(self, font, string, x, y, scale, colour, outline,
                      thickness=1, centre=False):
        """Text with a dark halo.

        Required, not decorative: the clock and date sit directly on the scene,
        and in the day theme that scene is a bright sky, so white text without a
        halo is unreadable. The mockups draw the same halo.
        """
        points = list(self.glyph_pixels(font, string, x, y, scale, centre))
        offsets = [(dx, dy)
                   for dy in range(-thickness, thickness + 1)
                   for dx in range(-thickness, thickness + 1)
                   if dx or dy]
        for dx, dy in offsets:
            for px_, py_ in points:
                self.blend(px_ + dx, py_ + dy, outline)
        for px_, py_ in points:
            self.blend(px_, py_, colour)

    def text(self, font, string, x, y, scale, colour, centre=False):
        """Draws `string` at integer `scale`, vertically centred on y."""
        for px_, py_ in self.glyph_pixels(font, string, x, y, scale, centre):
            self.blend(px_, py_, colour)

    def text_width(self, font, string, scale):
        return font.width(string) * scale


