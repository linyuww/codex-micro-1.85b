def rgb565(r: int, g: int, b: int) -> tuple:
    """Round-trip a colour through RGB565, as the panel will."""
    value = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
    return (((value >> 11) & 0x1F) << 3,
            ((value >> 5) & 0x3F) << 2,
            (value & 0x1F) << 3)


